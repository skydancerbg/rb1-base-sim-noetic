#!/usr/bin/env python3
"""Generate the display textures of the graded E2-v2 levels (materials/levels/).

    python3 make_display_textures.py --font /path/DejaVuSans.ttf 42.7 43.1 43.8 44.0 44.4 46.1

Every value, the normal one included, is drawn by this one function, so a measured run never mixes
textures from two drawing processes: 260 x 100 px, background (8, 22, 10), digits (90, 255, 120),
DejaVu Sans 73 px centred at (132, 52). These are the nearest settings to the hand-made P5.6 textures
(display_norm.png / display_anomaly.png, kept for the v1 states); that fit is not pixel-exact (mean
absolute difference 7 of 255), which is why E2-v2 calibrates on this generator's 42.7, not on the old one.

Writes textures/display_v<digits>.png and scripts/levels.material (one unlit material per value, named
Inspection/DisplayV<digits>, as display_level_sdf() in inspection_ctl.py expects).
"""

from __future__ import annotations

import argparse
import os
import re

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.realpath(__file__))
OUT = os.path.join(HERE, "materials", "levels")
SIZE, BACKGROUND, FOREGROUND = (260, 100), (8, 22, 10), (90, 255, 120)
FONT_PX, CENTRE = 73, (132, 52)

MATERIAL = """material Inspection/DisplayV{digits}
{{
  technique
  {{
    pass
    {{
      lighting off
      texture_unit
      {{
        texture display_v{digits}.png
      }}
    }}
  }}
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--font", required=True, help="DejaVuSans.ttf")
    parser.add_argument("values", nargs="+")
    args = parser.parse_args()
    font = ImageFont.truetype(args.font, FONT_PX)
    os.makedirs(os.path.join(OUT, "textures"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "scripts"), exist_ok=True)
    script = ["// Generated by make_display_textures.py (E2-v2 graded display levels). Unlit, like the P5.6 displays.\n"]
    for value in args.values:
        if not re.fullmatch(r"\d{1,3}\.\d", value):
            parser.error(f"value must look like 42.7: {value!r}")
        digits = value.replace(".", "")
        image = Image.new("RGB", SIZE, BACKGROUND)
        ImageDraw.Draw(image).text(CENTRE, value, font=font, fill=FOREGROUND, anchor="mm")
        image.save(os.path.join(OUT, "textures", f"display_v{digits}.png"), optimize=False)
        script.append(MATERIAL.format(digits=digits))
    with open(os.path.join(OUT, "scripts", "levels.material"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(script))
    print(f"{len(args.values)} textures in {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
